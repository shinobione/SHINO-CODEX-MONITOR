using System;
using System.Diagnostics;
using System.IO;
using System.Text;

namespace ShinoCodexMonitor
{
    // Installation is explicit, outside the running WinForms process.
    // The handoff rechecks the downloaded ZIP and only then executes the package installer.
    internal static class UpdateHandoff
    {
        internal static void Start(StagedUpdate update)
        {
            if (update == null || update.Asset == null || !File.Exists(update.Installer))
                throw new InvalidDataException("Update installation not prepared.");
            ReleasePackage.VerifyAssetFile(update.Asset, update.Archive);
            string ps1 = Path.Combine(update.Directory, "CONFIRMER-INSTALLATION.ps1");
            string script = @"param([int]$ParentPid, [string]$StagingDir, [string]$ZipName, [string]$Digest, [string]$InstallerName)
$ErrorActionPreference = 'Stop'
try {
  $zip = Join-Path $StagingDir $ZipName
  $installer = Join-Path (Join-Path $StagingDir 'package') $InstallerName
  if (!(Test-Path -LiteralPath $zip) -or !(Test-Path -LiteralPath $installer)) { throw 'Fichiers de mise a jour manquants.' }
  $hash = (Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash
  if ($hash -cne $Digest) { throw 'Empreinte ZIP differente : installation annulee.' }
  # Wait for the normal application to release its executable before installation.
  try { Wait-Process -Id $ParentPid -Timeout 25 -ErrorAction SilentlyContinue } catch { }
  if (Get-Process -Id $ParentPid -ErrorAction SilentlyContinue) { throw 'Le widget est encore actif. Installation annulee.' }
  Write-Host 'Installation confirmee de SHINO // CODEX MONITOR...' -ForegroundColor Cyan
  & $installer
  if ($LASTEXITCODE -ne 0) { throw 'Installer failed (see error above).' }
  Write-Host 'Installation terminee. Le widget a ete relance.' -ForegroundColor Green
  # Retain the staging files for diagnostic/rollback until the user chooses to remove them.
} catch { Write-Host ('ERROR: ' + $_.Exception.Message) -ForegroundColor Red; Read-Host 'Press Enter'; exit 1 }
";
            File.WriteAllText(ps1, script, new UTF8Encoding(true));
            string powershell = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows),
                @"System32\WindowsPowerShell\v1.0\powershell.exe");
            ProcessStartInfo info = new ProcessStartInfo {
                FileName = powershell,
                Arguments = "-NoLogo -NoProfile -ExecutionPolicy Bypass -File " + Q(ps1) +
                    " -ParentPid " + Process.GetCurrentProcess().Id +
                    " -StagingDir " + Q(update.Directory) +
                    " -ZipName " + Q(update.Asset.Name) +
                    " -Digest " + Q(update.Asset.Sha256.ToUpperInvariant()) +
                    " -InstallerName " + Q(Path.GetFileName(update.Installer)),
                UseShellExecute = false, CreateNoWindow = false,
                WorkingDirectory = update.Directory
            };
            if (Process.Start(info) == null) throw new IOException("Lancement de l'installateur impossible.");
        }
        // Paths generated by the app are restricted to a temporary GUID directory.
        private static string Q(string arg)
        {
            if (string.IsNullOrEmpty(arg) || arg.IndexOf('"') >= 0 || arg.IndexOf('\r') >= 0 || arg.IndexOf('\n') >= 0)
                throw new InvalidDataException("Chemin de mise a jour invalide.");
            return "\"" + arg + "\"";
        }
    }
}
